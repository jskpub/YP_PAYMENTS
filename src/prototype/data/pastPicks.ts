/** 최신 달이 위로 오도록 내림차순. 표지색은 달마다 팔레트 시작점을 옮겨 인접한 줄이 겹치지 않게 한다. */
export const PAST_MONTHLY_PICKS: PastMonthPicks[] = Object.keys(SEEDS)
  .map(Number)
  .sort((a, b) => b - a)
  .map((month, monthIndex) => ({
    month,
    books: SEEDS[month].map(([title, author, targetLabel], index) => ({
      id: `past-${String(month).padStart(2, '0')}-${String(index + 1).padStart(2, '0')}`,
      title,
      author,
      targetLabel,
      coverBackground: COVER[(monthIndex * 3 + index) % COVER.length],
    })),
  }));
